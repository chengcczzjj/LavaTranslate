// Windows native smoke test: run after npm run build. Briefly injects only the intercepted shortcut.
const assert = require('node:assert/strict')
const { app } = require('electron')
const { join } = require('node:path')
const { buildSync } = require('esbuild')
const { copyFileSync, mkdirSync } = require('node:fs')
const dir = join(__dirname, '../.scratch/win-space-check')
mkdirSync(dir, { recursive: true })
buildSync({ entryPoints: [join(__dirname, '../src/main/win-space.ts')], outfile: join(dir, 'win-space.cjs'), platform: 'node', format: 'cjs', bundle: true, external: ['koffi'] })
copyFileSync(join(__dirname, '../out/main/win-space-worker.js'), join(dir, 'win-space-worker.js'))
app.setPath('userData', join(dir, 'user-data'))
const { WinSpaceHotkey } = require(join(dir, 'win-space.cjs'))
const hook = new WinSpaceHotkey()
const delay = (ms) => new Promise((r) => setTimeout(r, ms))
const events = []
app.whenReady().then(async () => {
  assert.equal(await hook.start((recording) => events.push(recording)), true)
  console.log('hook ready')
  const user = require('koffi').load('user32.dll')
  const key = user.func('void __stdcall keybd_event(uint8_t key, uint8_t scan, uint32_t flags, uintptr_t extra)')
  const state = user.func('short __stdcall GetAsyncKeyState(int key)')
  const foreground = user.func('intptr_t __stdcall GetForegroundWindow()')
  const previousForeground = foreground()
  const getClass = user.func('int __stdcall GetClassNameW(intptr_t window, void *text, int size)')
  const classOf = (window) => { const buffer = Buffer.alloc(512); getClass(window, buffer, 256); return buffer.toString('utf16le').split('\0')[0] }
  console.log('foreground before:', classOf(previousForeground))
  hook.setMode(1)
  try {
    key(0x5b, 0, 0, 0)
    await delay(30)
    key(0x20, 0, 0, 0)
    await delay(60)
    key(0x20, 0, 0, 0)
    await delay(60)
    assert.deepEqual(events, [false], 'held Space only fires once')
    key(0x20, 0, 2, 0)
    await delay(30)
    key(0x20, 0, 0, 0)
    await delay(60)
    assert.deepEqual(events, [false, false], 'second press is delivered')
    key(0x20, 0, 2, 0)
    hook.setMode(2)
    await delay(30)
    key(0x20, 0, 0, 0)
    await delay(60)
    assert.deepEqual(events, [false, false, true], 'recording is forwarded without capture')
  } finally {
    key(0x20, 0, 2, 0)
    key(0x5b, 0, 2, 0)
    key(0x11, 0, 2, 0)
  }
  await delay(80)
  for (const vk of [0x20, 0x5b, 0x11]) assert.equal(state(vk) & 0x8000, 0, 'key released')
  console.log('foreground after:', classOf(foreground()))
  assert.equal(foreground(), previousForeground, 'releasing Win must not open Start')
  hook.stop()
  await delay(100)
  assert.equal(hook.setMode(1), false)
  console.log('Win+Space native checks passed: repeat, double press, recording, release, shutdown')
  app.exit(0)
}).catch((error) => { console.error(error); hook.stop(); app.exit(1) })
setTimeout(() => { console.error('timeout'); hook.stop(); app.exit(1) }, 10000)
